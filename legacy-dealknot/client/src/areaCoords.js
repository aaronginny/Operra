export function normalizeAreaKey(area) {
  return (area || "")
    .trim()
    .toLowerCase()
    .replace(/,\s*(chennai|chengalpattu|kanchipuram|tamil\s*nadu|india)\s*$/i, "")
    .trim();
}

export function getCoords(area) {
  return CHENNAI_COORDS[normalizeAreaKey(area)] || null;
}

export function haversineKm(lat1, lng1, lat2, lng2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

// Returns the closest area pair result or null
export function checkAreaProximity(buyerAreas, sellerAreas, radiusKm = 5) {
  let best = null;
  for (const ba of buyerAreas) {
    for (const sa of sellerAreas) {
      if (ba.toLowerCase() === sa.toLowerCase()) {
        return { buyerArea: ba, sellerArea: sa, distanceKm: 0, type: "exact" };
      }
      const bc = getCoords(ba);
      const sc = getCoords(sa);
      if (!bc || !sc) continue;
      const dist = haversineKm(bc.lat, bc.lng, sc.lat, sc.lng);
      if (dist <= radiusKm) {
        if (!best || dist < best.distanceKm) {
          best = { buyerArea: ba, sellerArea: sa, distanceKm: Math.round(dist * 10) / 10, type: "proximity" };
        }
      }
    }
  }
  return best;
}
